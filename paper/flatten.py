"""Build paper/paper_single.tex: main.tex with every \\input{...} replaced by the file's contents (recursively), so the whole paper is one .tex file.
Regenerate tables first, then run: python3 flatten.py   (then: tectonic paper_single.tex inside paper/)"""
import re
from pathlib import Path
D = Path(__file__).resolve().parent
def inline(text, depth=0):
    assert depth < 5
    def sub(m):
        f = D / m.group(1)
        return f"% ---- begin {m.group(1)} ----\n" + inline(f.read_text(), depth + 1).rstrip("\n") + f"\n% ---- end {m.group(1)} ----"
    return re.sub(r"\\input\{([^}]+)\}", sub, text)
out = inline((D / "main.tex").read_text())
(D / "paper_single.tex").write_text("% GENERATED by paper/flatten.py from main.tex and its \\input files; edit those, not this file.\n" + out)
print("paper_single.tex:", out.count("\n"), "lines;", len(re.findall(r"\\input\{", out)), "\\input left")
